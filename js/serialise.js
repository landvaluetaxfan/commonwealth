/* =============================================================
   SERIALISER — model back to content files.

   The editor's output must be byte-plausible content: the same
   shape a person would hand-write, so the files stay readable and
   diffable and you can always drop back to editing them directly.

   Author comments inside data cannot survive a round trip through
   objects, so each file gets a regenerated header instead.
   ============================================================= */

const Serialise = (function () {
  "use strict";

  const IDENT = /^[A-Za-z_$][A-Za-z0-9_$]*$/;

  function str(s) {
    if (String(s).includes("\n")) return "`" + String(s).replace(/`/g, "\\`").replace(/\$\{/g, "\\${") + "`";
    return '"' + String(s).replace(/\\/g, "\\\\").replace(/"/g, '\\"') + '"';
  }

  function val(v, ind, inline) {
    if (v === null) return "null";
    if (typeof v === "number" || typeof v === "boolean") return String(v);
    if (typeof v === "string") return str(v);
    if (Array.isArray(v)) {
      if (!v.length) return "[]";
      const flat = v.every(x => typeof x !== "object" || x === null);
      if (flat || inline) return "[" + v.map(x => val(x, ind, true)).join(",") + "]";
      return "[\n" + v.map(x => ind + "  " + val(x, ind + "  ")).join(",\n") + "\n" + ind + "]";
    }
    const keys = Object.keys(v).filter(k => v[k] !== undefined);
    if (!keys.length) return "{}";
    const short = keys.every(k => typeof v[k] !== "object" || v[k] === null) &&
                  keys.map(k => k + String(v[k])).join("").length < 70;
    const body = keys.map(k => (IDENT.test(k) ? k : str(k)) + ":" + val(v[k], ind + "  ", short || inline));
    if (short || inline) return "{ " + body.join(", ") + " }";
    return "{\n" + body.map(b => ind + "  " + b).join(",\n") + "\n" + ind + "}";
  }

  /* one entry per line-ish, matching the hand-written files */
  function list(name, arr, header) {
    return header + "\nconst " + name + " = [\n\n" +
      arr.map(o => "  " + val(o, "  ")).join(",\n\n") + "\n\n];\n";
  }

  const H = {
    events:
`/* ============================================================
   EVENTS — generated by the editor. Safe to hand-edit.
   Verbs: scalar loyalty law station seats flag unflag bill
          relationship coalition wire queue
   Conditions: minSitting maxSitting flags flagsAbsent scalarAbove
          scalarBelow lawIs lawAbove lawBelow loyaltyAbove
          loyaltyBelow billStage inGovernment
   prologue:N  fires in order at the start, teaching one cluster
   queuedOnly  reachable only from a queue effect
   ============================================================ */`,
    parties:
`/* PARTIES — generated by the editor.
   axes: ownership public|private · personhood expansionist|restrictionist
         sovereignty federal|station · closure closurist|integrationist
   aliases: press nicknames (bible 8.3) */`,
    stations:
`/* STATIONS AND CONSTITUENCIES — generated by the editor.
   Roster is frozen canon. Adding one is a deliberate act. */`,
    characters:
`/* CHARACTERS — generated by the editor. The fixed roster. */`,
    bills:
`/* BILLS — generated by the editor.
   stances: "for" | "against" | "abstain" | {for:n} | {forPct:0..1}
            | {free:true} | {popular:…, functional:…}
   dualMajority:true must carry separately on both benches. */`,
    functional:
`/* FUNCTIONAL CONSTITUENCIES — generated by the editor.
   franchise: licensure | corporate | union_bloc | residual
   held must reconcile with each party's functional seat count. */`,
    constituencies:
`/* CONSTITUENCIES — the district tier. Generated by the editor.
   magnitude sums to the district tier (140) and, per station, to that
   station's seat count. electorate is attested adults, not population.
   apportionment_ratio is NOT stored: Engine.apportionment() derives it. */`,
    glossary:
`/* GLOSSARY — generated by the editor.
   cluster: terms that cannot be taught apart count as ONE unit of
   teaching load. The rule is one cluster per event. */`
  };

  function file(kind, arr) {
    const name = { events:"EVENTS", parties:"PARTIES", stations:"STATIONS",
                   characters:"CHARACTERS", bills:"BILLS", glossary:"GLOSSARY",
                   functional:"FUNCTIONAL", constituencies:"CONSTITUENCIES" }[kind];
    return list(name, arr, H[kind]);
  }

  function partiesFile(parties, currents) {
    return list("PARTIES", parties, H.parties) + "\n" +
      list("CURRENTS", currents,
`/* CURRENTS — factions inside a party. Same four axes; a current
   that drifts far enough simply becomes a party above. */`);
  }

  function encyclopediaFile(enc) {
    return `/* =============================================================
   THE CONCORDANCE — in-world encyclopedia. Generated by the editor.

   A VIEW over content that already exists: parties, stations, bills,
   characters and glossary terms all get articles generated from their
   own data, with numbers read live from state. Hand-write an entry
   here only for prose the data cannot produce — history, controversy,
   the argument about the thing.

   IT IS NOT NEUTRAL. Banners are characterisation.
   ============================================================= */

const ENCYCLOPEDIA = {

  meta: ` + val(enc.meta, "  ") + `,

  /* Banner types. Keep this list short — each one is a piece of characterisation. */
  banners: ` + val(enc.banners, "  ") + `,

  /* Hand-written articles. Anything not listed is generated from data. */
  articles: [

` + enc.articles.map(a => "  " + val(a, "  ")).join(",\n\n") + `

  ]
};
`;
  }

  return { file, partiesFile, encyclopediaFile, val };
})();
if (typeof module !== "undefined") module.exports = Serialise;
